-- Outbox local para publicar cambios de scoring en la proyeccion de lectura de Query.
-- No crea dependencias hacia el esquema consulta ni requiere un broker externo.

CREATE TABLE evento_proyeccion_query (
    id_evento           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_evento         VARCHAR(32)  NOT NULL,
    id_agregado         BIGINT       NOT NULL,
    version_payload     SMALLINT     NOT NULL DEFAULT 1,
    payload             JSONB        NOT NULL,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'PENDIENTE',
    intentos            INTEGER      NOT NULL DEFAULT 0,
    proximo_intento     TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    id_concesion        UUID         NULL,
    concesion_hasta     TIMESTAMPTZ  NULL,
    codigo_ultimo_error VARCHAR(50)  NULL,
    ultimo_error        VARCHAR(500) NULL,
    creado_en           TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    actualizado_en      TIMESTAMPTZ  NOT NULL DEFAULT clock_timestamp(),
    entregado_en        TIMESTAMPTZ  NULL,

    CONSTRAINT uq_evento_proyeccion_query_agregado UNIQUE (tipo_evento, id_agregado),
    CONSTRAINT ck_evento_proyeccion_query_tipo
        CHECK (tipo_evento IN ('SOLICITANTE_PROYECTAR', 'EVALUACION_COMPLETADA')),
    CONSTRAINT ck_evento_proyeccion_query_agregado CHECK (id_agregado > 0),
    CONSTRAINT ck_evento_proyeccion_query_version CHECK (version_payload > 0),
    CONSTRAINT ck_evento_proyeccion_query_payload
        CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_evento_proyeccion_query_estado
        CHECK (estado IN ('PENDIENTE', 'ENTREGADO', 'ERROR_PERMANENTE')),
    CONSTRAINT ck_evento_proyeccion_query_intentos CHECK (intentos >= 0),
    CONSTRAINT ck_evento_proyeccion_query_concesion
        CHECK ((id_concesion IS NULL) = (concesion_hasta IS NULL)),
    CONSTRAINT ck_evento_proyeccion_query_concesion_estado
        CHECK (estado = 'PENDIENTE' OR id_concesion IS NULL),
    CONSTRAINT ck_evento_proyeccion_query_entregado
        CHECK ((estado = 'ENTREGADO') = (entregado_en IS NOT NULL)),
    CONSTRAINT ck_evento_proyeccion_query_error
        CHECK (estado <> 'ERROR_PERMANENTE' OR codigo_ultimo_error IS NOT NULL)
);

CREATE INDEX ix_evento_proyeccion_query_elegibles
    ON evento_proyeccion_query (proximo_intento, creado_en, id_evento)
    WHERE estado = 'PENDIENTE';
